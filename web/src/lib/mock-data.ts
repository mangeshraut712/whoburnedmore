/** Deterministic 24×7 circadian grid (avoids SSR/client hydration drift). */
function generateCircadianGrid(): HourlyBlock[] {
  const blocks: HourlyBlock[] = [];
  let seed = 0x9e3779b9;
  for (let day = 0; day < 7; day++) {
    for (let hour = 0; hour < 24; hour++) {
      seed = (seed * 1664525 + 1013904223) >>> 0;
      const unit = (seed % 1000) / 1000;
      const isLateNight = hour >= 22 || hour <= 2;
      const isAfternoon = hour >= 14 && hour <= 18;
      const baseTokens = isLateNight
        ? Math.floor(unit * 850_000 + 400_000)
        : isAfternoon
          ? Math.floor(unit * 600_000 + 200_000)
          : Math.floor(unit * 80_000);

      blocks.push({
        hour,
        dayOfWeek: day,
        tokens: baseTokens,
        costUSD: Number(((baseTokens / 1_000_000) * 8.5).toFixed(2)),
      });
    }
  }
  return blocks;
}

